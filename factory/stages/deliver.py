# E2E
# --------------------------------------------------------------------------

def run_e2e(ctx: Ctx):
    """e2e 스위트 실행. tests/e2e 가 없으면 건너뛴다(없는 걸 실패로 치지 않는다)."""
    from factory.stages.build import TestOutcome, run_tests

    e2e_dir = ctx.cfg.repo / "tests" / "e2e"
    if not e2e_dir.exists() or not any(e2e_dir.rglob("test_*.py")):
        return None
    return run_tests(ctx, nodes=["tests/e2e"])


def debug_e2e(ctx: Ctx, outcome) -> bool:
    from factory.stages.build import IMPL_TOOLS, SPEC_CONFLICT, restore_if_tampered, snapshot_tests

    before = snapshot_tests(ctx)
    saved = {rel: (ctx.cfg.repo / rel).read_bytes() for rel in before}
    log = git(ctx, "log", "--oneline", "-8").stdout

    res = ctx.worker.run(WorkerTask(
        prompt=prompt("debug_e2e", output=outcome.output, recent_commits=log),
        cwd=ctx.cfg.repo,
        allowed_tools=IMPL_TOOLS,
        timeout=ctx.cfg.limits.worker_timeout_s,
        label="debug_e2e",
    ))
    v = restore_if_tampered(ctx, before, saved)
    if v:
        ctx.log(f"  ⚠ E2E 디버그 중 테스트 무단 수정 → 되돌림: {', '.join(v)}")
    return res.ok and SPEC_CONFLICT not in res.text


# --------------------------------------------------------------------------
# 백로그 등록 — 루프가 발산하지 않게 하는 안전장치
# --------------------------------------------------------------------------

def raise_bug(ctx: Ctx, origin: Ticket, reason: str, evidence: str = "") -> Ticket:
    """자동으로 못 끝낸 것을 사람 검토 큐로 넘긴다.

    이게 없으면 루프는 같은 티켓에서 영원히 재시도하거나, 조용히 실패를 삼킨다.
    """
    bug = ctx.tracker.create(Ticket(
        type=TicketType.BUG.value,
        title=f"[자동] {origin.key} 실패: {reason[:60]}",
        description="\n".join([
            f"원인 티켓: {origin.key} — {origin.title}",
            f"FSM 전이: {origin.fsm_ref}",
            f"시도 횟수: {origin.attempts}",
            f"사유: {reason}",
            "",
            "```",
            evidence[-3000:],
            "```",
        ]),
        parent=origin.parent,
        fsm_ref=origin.fsm_ref,
        usecase_ref=origin.usecase_ref,
        labels=["auto", "needs-human"],
        dod_tests=list(origin.dod_tests),
    ))
    origin.status = Status.BLOCKED.value
    origin.last_error = reason
    ctx.tracker.update(origin)
    ctx.tracker.comment(origin.key, f"자동 처리 한계 도달 → {bug.key} 로 승격, BLOCKED 처리")
    ctx.log(f"  ⛔ {origin.key} BLOCKED → 백로그 {bug.key} 등록 ({reason[:80]})")
    return bug
